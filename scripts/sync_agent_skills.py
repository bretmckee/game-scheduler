"""Generate Copilot agent files from canonical DSH skill files.

Each agent has one canonical source: ``.agents/skills/<name>/SKILL.md``
(the DSH skill bundle). This script derives the Copilot agent file
``.github/agents/<name>.agent.md`` from it by:

- replacing the DSH YAML frontmatter with the sidecar
  ``scripts/agent-frontmatter/<name>.md`` (Copilot frontmatter:
  description + tools list),
- removing the ``<!-- dsh-adapter:begin --> ... <!-- dsh-adapter:end -->``
  block (DSH-only execution note and tool-mapping table),
- inserting a generated-file notice before the body.

Run with no arguments to (re)generate the agent files. Run with
``--check`` to verify the agent files are in sync (used by the
pre-commit hook; exits 1 with a short diff when they are not).

The script is pure stdlib so it runs in pre-commit's isolated
``language: python`` environment.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
AGENTS = ("task-researcher", "task-planner")
ADAPTER_RE = re.compile(
    r"^<!-- dsh-adapter:begin -->\n.*?^<!-- dsh-adapter:end -->\n\n?",
    re.DOTALL | re.MULTILINE,
)
NOTICE = (
    "<!-- GENERATED by scripts/sync_agent_skills.py from "
    ".agents/skills/{name}/SKILL.md - edit the skill file and re-run "
    "the script; do not edit this file directly. -->\n"
)


def strip_dsh_frontmatter(text: str) -> str:
    """Return the body following the leading YAML frontmatter block."""
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        msg = "missing DSH frontmatter (expected leading ---)"
        raise ValueError(msg)
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return "".join(lines[i + 1 :])
    msg = "unterminated DSH frontmatter"
    raise ValueError(msg)


def build_agent_file(name: str) -> str:
    """Build the expected Copilot agent file content for one agent."""
    skill = (REPO_ROOT / ".agents" / "skills" / name / "SKILL.md").read_text()
    frontmatter = (REPO_ROOT / "scripts" / "agent-frontmatter" / f"{name}.md").read_text()
    body = strip_dsh_frontmatter(skill)
    if "<!-- dsh-adapter:begin -->" not in body:
        msg = f"{name}: missing dsh-adapter:begin marker"
        raise ValueError(msg)
    if "<!-- dsh-adapter:end -->" not in body:
        msg = f"{name}: missing dsh-adapter:end marker"
        raise ValueError(msg)
    subbed = ADAPTER_RE.sub("", body)
    if subbed == body:
        msg = f"{name}: dsh-adapter block not removed"
        raise ValueError(msg)
    return frontmatter.rstrip("\n") + "\n\n" + NOTICE.format(name=name) + "\n" + subbed.lstrip("\n")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Sync generated Copilot agent files from DSH skills."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify agent files are in sync; exit 1 on drift",
    )
    args = parser.parse_args()
    stale: list[str] = []
    for name in AGENTS:
        agent_path = REPO_ROOT / ".github" / "agents" / f"{name}.agent.md"
        expected = build_agent_file(name)
        if args.check:
            current = agent_path.read_text()
            if current != expected:
                stale.append(name)
                diff = difflib.unified_diff(
                    current.splitlines(keepends=True),
                    expected.splitlines(keepends=True),
                    fromfile=str(agent_path) + " (current)",
                    tofile=str(agent_path) + " (generated)",
                )
                print("".join(list(diff)[:40]))
        else:
            agent_path.write_text(expected)
            print(f"wrote {agent_path.relative_to(REPO_ROOT)}")
    if args.check:
        if stale:
            print(
                "stale generated file(s): "
                + ", ".join(stale)
                + " - run `python scripts/sync_agent_skills.py` to regenerate."
            )
            return 1
        print("agent files in sync with DSH skill sources.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
